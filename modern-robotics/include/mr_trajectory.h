    /** @brief Computes the cubic time scaling factor s(t) for a given total time Tf and current time t.
     * This function is used in trajectory generation to ensure smooth start and stop of motion.
     * The output s(t) is a scalar that varies from 0 to 1 as t goes from 0 to Tf, following a cubic polynomial:
     * s(t) = a0 + a1*t + a2*t^2 + a3*t^3
     * Solving for boundary conditions s(0) = 0, s(Tf) = 1, s'(0) = 0, and s'(Tf) = 0, 
     * ensuring smooth acceleration and deceleration: s(t) = 3*(t/Tf)^2 - 2*(t/Tf)^3
     * @param Tf Total time for the trajectory.
     * @param t Current time (must be in the range [0, Tf]).
     * @return The cubic time scaling factor s(t).
     */
    inline double cubicTimeScaling(double Tf, double t) {
        if (t < 0 || t > Tf) {
            throw std::out_of_range("Time t must be in the range [0, Tf]");
        }
        return 3 * std::pow(t / Tf, 2) - 2 * std::pow(t / Tf, 3);
    }

    /** @brief Computes the quintic time scaling factor s(t) for a given total time Tf and current time t.
     *  This function is used in trajectory generation to ensure even smoother start and stop of motion compared to cubic scaling.
     *  The output s(t) is a scalar that varies from 0 to 1 as t goes from 0 to Tf, following a quintic polynomial:
     *  s(t) = a0 + a1*t + a2*t^2 + a3*t^3 + a4*t^4 + a5*t^5
     *  Solving for boundary conditions s(0) = 0, s(Tf) = 1, s'(0) = 0, s'(Tf) = 0, s''(0) = 0, and s''(Tf) = 0, 
     *  ensuring smooth acceleration, constant velocity, and deceleration phases: s(t) = 10*(t/Tf)^3 - 15*(t/Tf)^4 + 6*(t/Tf)^5 
     * @param Tf Total time for the trajectory.
     * @param t Current time (must be in the range [0, Tf]).
     * @return The quintic time scaling factor s(t).
     */
    inline double quinticTimeScaling(double Tf, double t) {
        if (t < 0 || t > Tf) {
            throw std::out_of_range("Time t must be in the range [0, Tf]");
        }
        return 10 * std::pow(t / Tf, 3) - 15 * std::pow(t / Tf, 4) + 6 * std::pow(t / Tf, 5);
    }

    /** @brief Generates a trajectory of SE(3) transformations from a start configuration to an end configuration using screw motion interpolation.
     * This function computes a sequence of N SE(3) transformations that smoothly transition from X_start to X_end over a total time Tf.
     * The method parameter determines whether to use cubic or quintic time scaling for the interpolation.
     * The trajectory is generated by computing the screw axis and angle that represent the motion from X_start to X_end, 
     * and then applying the appropriate time scaling to create intermediate configurations along the path.
     * @param X_start The initial SE(3) transformation in the eyes of the end-effector
     * @param X_end The final SE(3) transformation in the eyes of the end-effector
     * @param Tf Total time for the trajectory.
     * @param N Number of discrete points in the trajectory (including start and end).
     * @param method Time scaling method: 3 for cubic, 5 for quintic.
     * @return A vector of SE(3) transformations representing the trajectory from X_start to X_end.
     */
    inline std::vector<Eigen::Matrix4d> ScrewTrajectory(const Eigen::Matrix4d& X_start, const Eigen::Matrix4d& X_end,
         double Tf, int N, int method) {
        
        std::vector<Eigen::Matrix4d> trajectory;
        trajectory.reserve(N);
        
        double timegap = Tf / (N - 1);
        for (int i = 0; i < N; ++i) {
            double t = i * timegap;
            double s = (method == 3) ? cubicTimeScaling(Tf, t) : quinticTimeScaling(Tf, t);
            
            /** First calculate the T needed to go from X_start to X_end, which is T = X_start.inverse() * X_end.
             * Then calculate the matrix logarithm of T, which gives us the twist coordinates (screw axis and angle) 
             * that represent the motion from X_start to X_end.
             * Finally, we compute the intermediate transformation at time t by applying the exponential map to the 
             * scaled twist coordinates: X_start * exp(s * log(T)). This gives us the SE(3) transformation that is s
             * fraction of the way along the screw motion from X_start to X_end at time t. 
             * By iterating this process for each time step, we generate the full trajectory.
             * 
             */
            trajectory.push_back(X_start*(MatrixExp6(MatrixLog6(X_start.inverse() * X_end) * s)));
        }
        return trajectory;
    }

    /** @brief Generates a Cartesian space trajectory (stright line) from a start configuration to an end 
     * configuration using either cubic or quintic time scaling.
     * This function computes a sequence of N SE(3) transformations that smoothly transition from X_start 
     * to X_end over a total time Tf. The method parameter determines whether to use cubic or 
     * quintic time scaling for the interpolation. The trajectory is generated by interpolating the rotation
     * and translation components separately, using the chosen time scaling function to create intermediate 
     * configurations along the path.
     * @param X_start The initial SE(3) transformation in the eyes of the end-effector
     * @param X_end The final SE(3) transformation in the eyes of the end-effector
     * @param Tf Total time for the trajectory.
     * @param N Number of discrete points in the trajectory (including start and end).
     * @param method Time scaling method: 3 for cubic, 5 for quintic.
     * @return A vector of SE(3) transformations representing the trajectory from X_start to X_end.
     */
    inline std::vector<Eigen::Matrix4d> CartesianTrajectory(const Eigen::Matrix4d& X_start, const Eigen::Matrix4d& X_end,
         double Tf, int N, int method) {
        
        std::vector<Eigen::Matrix4d> trajectory;
        trajectory.reserve(N);

        auto [Rstart, pstart] = TransToRp(X_start);
        auto [Rend, pend] = TransToRp(X_end);
        
        double timegap = Tf / (N - 1);
        for (int i = 0; i < N; ++i) {
            double t = i * timegap;
            double s = (method == 3) ? cubicTimeScaling(Tf, t) : quinticTimeScaling(Tf, t);
            
            Eigen::Matrix3d R_interp = Rstart * MatrixExp3(MatrixLog3(Rstart.transpose() * Rend) * s);
            Eigen::Vector3d p_interp = pstart + s * (pend - pstart);
            trajectory.push_back(RpToTrans(R_interp, p_interp));
        }
        return trajectory;
    }

    /** @brief Generates a joint space trajectory from a start configuration to an end configuration using either cubic or quintic time scaling.
     * This function computes a sequence of N joint configurations that smoothly transition from theta_start to theta
     * end over a total time Tf. The method parameter determines whether to use cubic or quintic time scaling for the interpolation.
     * The trajectory is generated by applying the chosen time scaling function to interpolate between the start and end joint angles,
     * creating a smooth path in joint space that can be followed by the robot's actuators.
     * @param theta_start The initial joint configuration (vector of joint angles).
     * @param theta_end The final joint configuration (vector of joint angles).
     * @param Tf Total time for the trajectory.
     * @param N Number of discrete points in the trajectory (including start and end).
     * @param method Time scaling method: 3 for cubic, 5 for quintic
     * @return A vector of joint configurations representing the trajectory from theta_start to theta_end.
     * @note use this function for generating trajectories in joint space, where the robot's motion is defined 
     * by the angles of its joints rather than the position and orientation of its end-effector.
     * For example - lifting a box above the table - you don't need  to specify the exact path of the end-effector, 
     * but you do need to specify how the joints should move to achieve the desired motion.
     */
    inline std::vector<Eigen::VectorXd> JointTrajectory(const Eigen::VectorXd& theta_start, const Eigen::VectorXd& theta_end,
         double Tf, int N, int method) {
        
        std::vector<Eigen::VectorXd> trajectory;
        trajectory.reserve(N);

        double timegap = Tf / (N - 1);
        for (int i = 0; i < N; ++i) {
            double t = i * timegap;
            double s = (method == 3) ? cubicTimeScaling(Tf, t) : quinticTimeScaling(Tf, t);
            
            Eigen::VectorXd theta_interp = theta_start + s * (theta_end - theta_start);
            trajectory.push_back(theta_interp);
        }
        return trajectory;
    }
